ResourceModifiers
resources(std::initializer_list<std::pair<ResourceType, double>> mods) {
    ResourceModifiers out = {1, 1, 1, 1, 1, 1, 1};
    for (auto [resource, mod] : mods) {
        out[resource] = mod;
    }
    return out;
}
